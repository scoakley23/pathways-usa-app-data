#!/usr/bin/env node
// Builds src/data/zipDistricts.json: every ZIP code area (Census ZCTA) and the
// congressional district(s) it lies in, from the Census Bureau's official
// relationship file. No key, no AI. See scripts/districts/README.md.
//
//   node scripts/districts/build-zip-districts.mjs                 (119th Congress)
//   node scripts/districts/build-zip-districts.mjs --congress 120  (after redistricting)
//   node scripts/districts/build-zip-districts.mjs --file path/to/tab20_cd11920_zcta520_natl.txt
//
// A ZIP is listed under every district that holds any of its land; a part
// that is only water is left out. A ZIP under two or more districts is
// "split": the app then asks for the street address instead of guessing.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const OUT = path.resolve(HERE, '../../src/data/zipDistricts.json');

export const FIPS = {
  '01': 'AL', '02': 'AK', '04': 'AZ', '05': 'AR', '06': 'CA', '08': 'CO', '09': 'CT', '10': 'DE', '11': 'DC',
  '12': 'FL', '13': 'GA', '15': 'HI', '16': 'ID', '17': 'IL', '18': 'IN', '19': 'IA', '20': 'KS', '21': 'KY',
  '22': 'LA', '23': 'ME', '24': 'MD', '25': 'MA', '26': 'MI', '27': 'MN', '28': 'MS', '29': 'MO', '30': 'MT',
  '31': 'NE', '32': 'NV', '33': 'NH', '34': 'NJ', '35': 'NM', '36': 'NY', '37': 'NC', '38': 'ND', '39': 'OH',
  '40': 'OK', '41': 'OR', '42': 'PA', '44': 'RI', '45': 'SC', '46': 'SD', '47': 'TN', '48': 'TX', '49': 'UT',
  '50': 'VT', '51': 'VA', '53': 'WA', '54': 'WV', '55': 'WI', '56': 'WY',
  '60': 'AS', '66': 'GU', '69': 'MP', '72': 'PR', '78': 'VI',
};

// Census district code → the officeholders table's: "00" (at-large) and
// "98" (delegate / resident commissioner) → "At-large"; "ZZ" (water) → null.
export function districtCode(cd) {
  if (cd === 'ZZ') return null;
  if (cd === '00' || cd === '98') return 'At-large';
  const n = parseInt(cd, 10);
  return Number.isNaN(n) ? null : String(n);
}

// The relationship file's text → { "TX": { "24": ["75001", …] }, … }.
export function parseRelationship(text, congress) {
  const lines = text.replace(/^﻿/, '').split(/\r?\n/).filter(Boolean);
  const head = lines[0].split('|');
  const col = (name) => head.indexOf(name);
  const cdCol = col(`GEOID_CD${congress}_20`);
  const zipCol = col('GEOID_ZCTA5_20');
  const landCol = col('AREALAND_PART');
  if (cdCol < 0 || zipCol < 0 || landCol < 0) throw new Error(`Not a ${congress}th Congress ZCTA relationship file.`);
  const out = {};
  for (const line of lines.slice(1)) {
    const r = line.split('|');
    const zip = r[zipCol];
    if (!zip || !(Number(r[landCol]) > 0)) continue;
    const state = FIPS[r[cdCol].slice(0, 2)];
    const district = districtCode(r[cdCol].slice(2));
    if (!state || !district) continue;
    const s = (out[state] ||= {});
    (s[district] ||= new Set()).add(zip);
  }
  // Sorted, as space-separated strings (small file, stable diffs).
  return Object.fromEntries(Object.keys(out).sort().map((st) => [st, Object.fromEntries(
    Object.keys(out[st]).sort((a, b) => (a === 'At-large' ? -1 : b === 'At-large' ? 1 : Number(a) - Number(b)))
      .map((d) => [d, [...out[st][d]].sort().join(' ')]),
  )]));
}

async function main() {
  const args = process.argv.slice(2);
  const opt = (name, fallback) => { const i = args.indexOf(name); return i >= 0 ? args[i + 1] : fallback; };
  const congress = opt('--congress', '119');
  const file = opt('--file', null);
  const source = `https://www2.census.gov/geo/docs/maps-data/data/rel2020/cd-sld/tab20_cd${congress}20_zcta520_natl.txt`;
  let text;
  if (file) text = fs.readFileSync(file, 'utf8');
  else {
    console.log(`Downloading ${source}…`);
    const res = await fetch(source);
    if (!res.ok) throw new Error(`Census download failed (${res.status}). Is the ${congress}th Congress file published yet?`);
    text = await res.text();
  }
  const states = parseRelationship(text, congress);
  const zips = new Map();
  for (const [st, ds] of Object.entries(states)) for (const [d, list] of Object.entries(ds)) for (const z of list.split(' ')) zips.set(z, (zips.get(z) || 0) + 1);
  const split = [...zips.values()].filter((n) => n > 1).length;
  const table = {
    meta: {
      congress: Number(congress),
      source,
      built: new Date().toISOString().slice(0, 10),
      note: 'ZIP code areas (Census ZCTAs, 2020) by congressional district. Generated by scripts/districts/build-zip-districts.mjs; do not edit by hand. A ZIP listed under more than one district is split: the app asks for the street address.',
      zips: zips.size,
      split,
    },
    states,
  };
  fs.writeFileSync(OUT, `${JSON.stringify(table)}\n`);
  console.log(`Wrote ${path.relative(process.cwd(), OUT)}: ${zips.size} ZIPs, ${split} split, ${Object.keys(states).length} states and territories.`);
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  main().catch((err) => { console.error(err.message || err); process.exit(1); });
}
