// Bundles src/lib/aiServer.js (and everything it uses: the prompt builders,
// the official 2025 civics list, the officeholder table, the N-400 guide's
// officer phrasings) into one file the `ai` Edge Function imports:
// supabase/functions/_shared/aiServer.generated.js. Run it after changing any
// of those, including the monthly officeholder update, then redeploy:
//   npm run ai:server
//   supabase functions deploy ai
// src/lib/aiServer.test.js fails while the bundle is out of date.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { build } from 'esbuild';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
export const OUT_FILE = path.join(ROOT, 'supabase/functions/_shared/aiServer.generated.js');

const BANNER = `// GENERATED by scripts/supabase/build-ai-server.mjs from src/lib/aiServer.js.
// Do not edit: run \`npm run ai:server\` instead.`;

export async function bundleAiServer() {
  const result = await build({
    entryPoints: [path.join(ROOT, 'src/lib/aiServer.js')],
    bundle: true,
    format: 'esm',
    platform: 'neutral',
    target: 'es2022',
    write: false,
    legalComments: 'none',
    charset: 'utf8',
    banner: { js: BANNER },
    logLevel: 'silent',
  });
  // Paths in esbuild's comments are relative to the working directory.
  return result.outputFiles[0].text;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const text = await bundleAiServer();
  fs.writeFileSync(OUT_FILE, text);
  console.log(`Wrote ${path.relative(ROOT, OUT_FILE)} (${Math.round(text.length / 1024)} KB)`);
}
