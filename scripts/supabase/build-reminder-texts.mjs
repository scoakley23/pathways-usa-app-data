// Writes supabase/functions/_shared/reminderTexts.generated.js: the pilot
// reminder email's subject and body (REMINDER_SUBJECT / REMINDER_BODY in
// base44/shared/pilotCheckIns.js) in every language the translation pack
// has both for (content/translations/reviewed/{lang}.json wins over
// {lang}.json). Lines that drop {link} or use a word the email must never
// use are left out (English is sent instead). Run after building the pack:
//   npm run email:texts
//   supabase functions deploy pilot-reminders
// src/lib/emails.test.js fails while this file is out of date.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { FORBIDDEN_EMAIL_WORDS, REMINDER_BODY, REMINDER_SUBJECT } from '../../base44/shared/pilotCheckIns.js';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
const DIR = path.join(ROOT, 'content/translations');
export const OUT_FILE = path.join(ROOT, 'supabase/functions/_shared/reminderTexts.generated.js');

const read = (file) => {
  try {
    return JSON.parse(fs.readFileSync(file, 'utf8')).strings || {};
  } catch (e) {
    return {};
  }
};

export function reminderTexts() {
  const langs = fs.readdirSync(DIR).filter((f) => f.endsWith('.json') && !f.startsWith('_')).map((f) => f.slice(0, -5)).sort();
  const out = {};
  for (const lang of langs) {
    const machine = read(path.join(DIR, `${lang}.json`));
    const reviewed = read(path.join(DIR, 'reviewed', `${lang}.json`));
    const pick = (en) => reviewed[en] ?? machine[en];
    const subject = pick(REMINDER_SUBJECT);
    const body = pick(REMINDER_BODY);
    if (typeof subject !== 'string' || typeof body !== 'string' || !body.includes('{link}')) continue;
    if (FORBIDDEN_EMAIL_WORDS.test(subject) || FORBIDDEN_EMAIL_WORDS.test(body)) continue;
    out[lang] = { subject, body };
  }
  return out;
}

export function reminderTextsModule() {
  return `// GENERATED by scripts/supabase/build-reminder-texts.mjs from the translation
// pack. Do not edit: run \`npm run email:texts\` instead.
export const REMINDER_TEXTS = ${JSON.stringify(reminderTexts(), null, 2)};
`;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  fs.writeFileSync(OUT_FILE, reminderTextsModule());
  console.log(`Wrote ${path.relative(ROOT, OUT_FILE)} (${Object.keys(reminderTexts()).length} languages)`);
}
