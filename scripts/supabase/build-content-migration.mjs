#!/usr/bin/env node
// Builds supabase/migrations/20261114000003_content.sql from the Base44
// content export (content/base44-export/), so `supabase db push` loads the
// real content (questions, sentences, words, lessons, flashcards, places).
// Re-run after re-exporting; the migration is generated, never hand-edited.
//
//   node scripts/supabase/build-content-migration.mjs
//
// Not loaded: LessonQuiz (no screen uses it; kept in the repo as JSON) and
// the -orphaned files (their lesson was deleted in Base44).

import fs from 'fs';
import path from 'path';

const ROOT = path.resolve(path.dirname(new URL(import.meta.url).pathname), '../..');
const SRC = path.join(ROOT, 'content/base44-export');
export const OUT = path.join(ROOT, 'supabase/migrations/20261114000003_content.sql');

// [table, file(s), columns as [sql column, json field, kind]]
export const TABLES = [
  ['civics_questions', ['civics-questions-2008.json', 'civics-questions-2025.json'],
    [['id', 'id'], ['version', 'version'], ['question', 'question'], ['answer', 'answer'], ['category', 'category'], ['difficulty', 'difficulty']]],
  ['interview_questions', ['interview-questions.json'],
    [['id', 'id'], ['section', 'section'], ['question', 'question'], ['expected_response', 'expected_response'],
      ['response_type', 'response_type'], ['sort_order', 'order', 'int'], ['tips', 'tips']]],
  ['reading_sentences', ['reading-sentences.json'], [['id', 'id'], ['text', 'text'], ['difficulty', 'difficulty']]],
  ['writing_sentences', ['writing-sentences.json'], [['id', 'id'], ['text', 'text'], ['category', 'category'], ['difficulty', 'difficulty']]],
  ['vocabulary_words', ['vocabulary-words.json'], [['id', 'id'], ['word', 'word'], ['category', 'category'], ['definition', 'definition']]],
  ['lessons', ['lessons.json'],
    [['id', 'id'], ['topic', 'topic'], ['title', 'title'], ['description', 'description'], ['video_url', 'video_url'],
      ['content', 'content'], ['key_points', 'key_points', 'jsonb'], ['sort_order', 'order', 'int']]],
  ['lesson_flashcards', ['lesson-flashcards.json'],
    [['id', 'id'], ['lesson_id', 'lesson_id'], ['term', 'term'], ['definition', 'definition'], ['example', 'example']]],
  ['community_resources', ['community-resources.json'],
    [['id', 'id'], ['name', 'name'], ['category', 'category'], ['services', 'services', 'text[]'], ['address', 'address'],
      ['city', 'city'], ['state', 'state'], ['zip', 'zip'], ['latitude', 'latitude', 'num'], ['longitude', 'longitude', 'num'],
      ['location_precision', 'location_precision'], ['phone', 'phone'], ['website', 'website'], ['logo_url', 'logo_url'],
      ['hours', 'hours'], ['languages', 'languages', 'text[]'], ['cost', 'cost'], ['description', 'description'],
      ['source', 'source'], ['source_url', 'source_url'], ['last_verified', 'last_verified'],
      ['external_id', 'external_id', 'nullable'], ['relevance_note', 'relevance_note'], ['is_active', 'is_active', 'bool']]],
];

const str = (s) => `'${String(s).replace(/'/g, "''")}'`;

export function literal(value, kind) {
  if (value === null || value === undefined) return 'null';
  switch (kind) {
    case 'int':
    case 'num': return Number.isFinite(Number(value)) && value !== '' ? String(Number(value)) : 'null';
    case 'bool': return value ? 'true' : 'false';
    case 'jsonb': return `${str(JSON.stringify(value))}::jsonb`;
    case 'text[]': return Array.isArray(value) ? `array[${value.map(str).join(', ')}]::text[]` : 'null';
    case 'nullable': return value === '' ? 'null' : str(value);
    default: return str(value);
  }
}

export function buildSql() {
  const parts = [
    '-- GENERATED by scripts/supabase/build-content-migration.mjs from content/base44-export/.',
    '-- The app\'s shared content, exported from Base44 on Nov 13, 2026. Do not edit by hand.',
    '',
  ];
  const counts = {};
  for (const [table, files, cols] of TABLES) {
    const rows = files.flatMap((f) => JSON.parse(fs.readFileSync(path.join(SRC, f), 'utf8')));
    counts[table] = rows.length;
    for (let i = 0; i < rows.length; i += 200) {
      const batch = rows.slice(i, i + 200).map((r) => `  (${cols.map(([, field, kind]) => literal(r[field], kind)).join(', ')})`);
      parts.push(`insert into public.${table} (${cols.map(([c]) => c).join(', ')}) values\n${batch.join(',\n')};`, '');
    }
  }
  return { sql: parts.join('\n'), counts };
}

if (process.argv[1] && path.resolve(process.argv[1]) === path.resolve(new URL(import.meta.url).pathname)) {
  const { sql, counts } = buildSql();
  fs.writeFileSync(OUT, sql);
  console.log(Object.entries(counts).map(([t, n]) => `${t}: ${n}`).join('\n'));
}
